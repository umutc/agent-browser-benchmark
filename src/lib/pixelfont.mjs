export function textToRects(text, scale = 10, padding = 20) {
  const rects = [];
  [...text].forEach((char, index) => {
    const glyph = GLYPHS[char];
    if (!glyph) throw new Error(`no glyph for ${char}`);
    glyph.forEach((row, y) => {
      [...row].forEach((cell, x) => {
        if (cell === '#') rects.push([padding + (index * 7 + x) * scale, padding + y * scale, scale, scale]);
      });
    });
  });
  const width = padding * 2 + (text.length * 7 - 2) * scale;
  const height = padding * 2 + 7 * scale;
  return { rects, width, height };
}
